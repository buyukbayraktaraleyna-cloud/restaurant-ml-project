def translate(key, language, **params):
    """Return the text for `key` in `language` (English if the key is missing)."""
    text = TEXTS.get(language, {}).get(key)
    if text is None:
        text = TEXTS[DEFAULT_LANGUAGE].get(key, key)
    # Markup.format escapes the values, so user input cannot inject HTML
    return Markup(text).format(**params)
